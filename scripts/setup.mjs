#!/usr/bin/env node
// Interactive one-command bootstrap for reviewers.
//   npm run setup
// Asks for a database (Docker or an existing local Postgres), generates secrets,
// writes .env, runs migrations, optionally seeds, and optionally starts the app.
// Uses only Node built-ins (+ the already-installed `pg`) — no extra deps.

import { createInterface } from 'node:readline';
import { randomBytes } from 'node:crypto';
import { spawnSync, execSync } from 'node:child_process';
import { existsSync, writeFileSync, readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const ENV_PATH = join(ROOT, '.env');
const DOCKER_DB_URL = 'postgres://app:app@localhost:5432/seo_tracker'; // matches docker-compose.yml

// Buffer input lines in a queue so answers are never lost in the async gaps
// between prompts (robust for both interactive typing and piped stdin).
const rl = createInterface({ input: process.stdin });
const lineQueue = [];
const waiters = [];
rl.on('line', (line) => (waiters.length ? waiters.shift()(line) : lineQueue.push(line)));
rl.on('close', () => waiters.splice(0).forEach((w) => w('')));
const nextLine = () =>
  new Promise((resolve) => (lineQueue.length ? resolve(lineQueue.shift()) : waiters.push(resolve)));
const ask = async (q, def = '') => {
  process.stdout.write(def ? `${q} [${def}]: ` : `${q}: `);
  const a = (await nextLine()).trim();
  return a || def;
};
const askYN = async (q, def = true) => {
  const a = (await ask(`${q} (${def ? 'Y/n' : 'y/N'})`)).toLowerCase();
  return a ? ['y', 'yes', 's', 'sim'].includes(a) : def;
};
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const die = (m) => {
  console.error(`\n✖ ${m}`);
  rl.close();
  process.exit(1);
};

function run(cmd, args) {
  // shell:true so `npm`/`docker` resolve on Windows (npm.cmd) and Unix alike.
  const r = spawnSync(cmd, args, { stdio: 'inherit', cwd: ROOT, shell: true });
  if (r.status !== 0) die(`\`${cmd} ${args.join(' ')}\` failed.`);
}
function hasCommand(cmd) {
  try {
    execSync(process.platform === 'win32' ? `where ${cmd}` : `command -v ${cmd}`, { stdio: 'ignore' });
    return true;
  } catch {
    return false;
  }
}

function buildEnv({ databaseUrl, sessionSecret, seedPassword }) {
  return `# Generated by \`npm run setup\`. Safe to edit; never commit this file.
NODE_ENV=development
DATABASE_URL=${databaseUrl}
PORT=4000
SESSION_SECRET=${sessionSecret}
WEB_ORIGIN=http://localhost:5173
APP_TIMEZONE=America/Toronto
# Login password for the two demo accounts the seed creates.
SEED_PASSWORD=${seedPassword}
`;
}

function readEnvValue(key) {
  if (!existsSync(ENV_PATH)) return null;
  const line = readFileSync(ENV_PATH, 'utf8')
    .split('\n')
    .find((l) => l.startsWith(`${key}=`));
  return line ? line.slice(key.length + 1).trim() : null;
}

async function waitForDb(url) {
  let Client;
  try {
    const pg = await import('pg');
    Client = (pg.default ?? pg).Client;
  } catch {
    return; // pg not resolvable — skip the pre-check; migrate will surface errors
  }
  process.stdout.write('Waiting for the database');
  for (let i = 0; i < 30; i++) {
    const client = new Client({ connectionString: url, connectionTimeoutMillis: 2000 });
    try {
      await client.connect();
      await client.end();
      console.log(' ✓');
      return;
    } catch {
      await client.end().catch(() => {});
      process.stdout.write('.');
      await sleep(1000);
    }
  }
  die('Database not reachable. Is it running and are the connection details correct?');
}

async function main() {
  console.log('\nSEO Keyword Tracker — setup\n');

  if (!existsSync(join(ROOT, 'node_modules'))) {
    console.log('Installing dependencies (npm install)…');
    run('npm', ['install']);
  }

  let writeEnv = true;
  if (existsSync(ENV_PATH)) {
    writeEnv = await askYN('.env already exists. Overwrite it?', false);
  }

  let databaseUrl = readEnvValue('DATABASE_URL');
  let seedPassword = null;

  if (writeEnv) {
    console.log('\nDatabase:');
    console.log('  1) Docker — start Postgres via docker compose (recommended)');
    console.log('  2) Local  — use a Postgres you already run');
    const choice = await ask('Choose 1 or 2', '1');

    if (choice === '2') {
      const host = await ask('  host', 'localhost');
      const port = await ask('  port', '5432');
      const user = await ask('  user', 'postgres');
      const pass = await ask('  password', '');
      const db = await ask('  database', 'seo_tracker');
      const auth = pass ? `${user}:${encodeURIComponent(pass)}` : user;
      databaseUrl = `postgres://${auth}@${host}:${port}/${db}`;
    } else {
      if (!hasCommand('docker')) {
        die('Docker not found. Install Docker, or re-run and choose the Local option.');
      }
      console.log('\nStarting Postgres (docker compose up -d db)…');
      run('docker', ['compose', 'up', '-d', 'db']);
      databaseUrl = DOCKER_DB_URL;
    }

    const sessionSecret = randomBytes(32).toString('hex'); // 64 chars (>= 32 required)
    seedPassword = `demo-${randomBytes(4).toString('hex')}`;
    writeFileSync(ENV_PATH, buildEnv({ databaseUrl, sessionSecret, seedPassword }));
    console.log('\n✓ Wrote .env (secrets generated).');
  } else {
    console.log('Keeping the existing .env.');
  }

  if (!databaseUrl) die('No DATABASE_URL found. Re-run and let setup write the .env.');

  console.log('');
  await waitForDb(databaseUrl);

  console.log('\nApplying migrations…');
  run('npm', ['run', 'migrate']);

  if (await askYN('\nRun the seed now? It crawls semrush.com and yoast.com (~1–2 min)', true)) {
    run('npm', ['run', 'seed']);
  } else {
    console.log('Skipping seed. Run it later with:  npm run seed');
  }

  console.log('\n──────────────────────────────');
  console.log('Demo accounts:');
  console.log('  demo@semrush.com   (Semrush)');
  console.log('  demo@yoast.com     (Yoast)');
  console.log(seedPassword ? `  password: ${seedPassword}` : '  password: your SEED_PASSWORD in .env');
  console.log('──────────────────────────────');

  if (await askYN('\nStart the app now (npm run dev)?', true)) {
    rl.close();
    run('npm', ['run', 'dev']); // runs until Ctrl-C
  } else {
    console.log('\nAll set. Start it anytime with:  npm run dev\n');
    rl.close();
  }
}

main().catch((err) => die(err instanceof Error ? err.message : String(err)));
